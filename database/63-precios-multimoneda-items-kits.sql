BEGIN;

-- Los precios existentes continúan siendo ARS y calculados desde costo.
ALTER TABLE public.producto_precio
  ADD COLUMN IF NOT EXISTS modo_calculo text NOT NULL DEFAULT 'MARGEN_COSTO',
  ADD COLUMN IF NOT EXISTS importe_origen numeric,
  ADD COLUMN IF NOT EXISTS moneda_origen text,
  ADD COLUMN IF NOT EXISTS referencia_cotizacion text,
  ADD COLUMN IF NOT EXISTS lado_cotizacion text,
  ADD COLUMN IF NOT EXISTS tipo_recargo_cotizacion text,
  ADD COLUMN IF NOT EXISTS recargo_cotizacion numeric,
  ADD COLUMN IF NOT EXISTS cotizacion_usada numeric,
  ADD COLUMN IF NOT EXISTS actualizado_origen_at timestamptz;

ALTER TABLE public.producto_precio
  DROP CONSTRAINT IF EXISTS producto_precio_modo_calculo_check;
ALTER TABLE public.producto_precio
  ADD CONSTRAINT producto_precio_modo_calculo_check
  CHECK (modo_calculo IN ('MARGEN_COSTO', 'FIJO_ARS', 'FIJO_MONEDA'));

ALTER TABLE public.producto_precio
  DROP CONSTRAINT IF EXISTS producto_precio_moneda_origen_check;
ALTER TABLE public.producto_precio
  ADD CONSTRAINT producto_precio_moneda_origen_check
  CHECK (moneda_origen IS NULL OR moneda_origen IN ('ARS', 'USD', 'EUR', 'BRL'));

ALTER TABLE public.producto_precio
  DROP CONSTRAINT IF EXISTS producto_precio_referencia_cotizacion_check;
ALTER TABLE public.producto_precio
  ADD CONSTRAINT producto_precio_referencia_cotizacion_check
  CHECK (referencia_cotizacion IS NULL OR referencia_cotizacion IN ('OFICIAL', 'BLUE', 'MEP', 'CCL'));

ALTER TABLE public.producto_precio
  DROP CONSTRAINT IF EXISTS producto_precio_lado_cotizacion_check;
ALTER TABLE public.producto_precio
  ADD CONSTRAINT producto_precio_lado_cotizacion_check
  CHECK (lado_cotizacion IS NULL OR lado_cotizacion IN ('COMPRA', 'VENTA'));

ALTER TABLE public.producto_precio
  DROP CONSTRAINT IF EXISTS producto_precio_tipo_recargo_cotizacion_check;
ALTER TABLE public.producto_precio
  ADD CONSTRAINT producto_precio_tipo_recargo_cotizacion_check
  CHECK (tipo_recargo_cotizacion IS NULL OR tipo_recargo_cotizacion IN ('PORCENTAJE', 'MONTO_FIJO'));

UPDATE public.producto_precio
SET modo_calculo = CASE
  WHEN id_tipo_precio = (
    SELECT id FROM public.tipo_precio WHERE upper(trim(descripcion)) = 'PRECIO COSTO' ORDER BY id LIMIT 1
  )
  AND EXISTS (
    SELECT 1 FROM public.productos producto
    WHERE producto.id = producto_precio.id_producto AND producto.criterio_costo = 'MANUAL'
  ) THEN 'FIJO_ARS'
  ELSE 'MARGEN_COSTO'
END,
importe_origen = precio,
moneda_origen = CASE
  WHEN id_tipo_precio = (
    SELECT id FROM public.tipo_precio WHERE upper(trim(descripcion)) = 'PRECIO COSTO' ORDER BY id LIMIT 1
  )
  AND EXISTS (
    SELECT 1 FROM public.productos producto
    WHERE producto.id = producto_precio.id_producto AND producto.criterio_costo = 'MANUAL'
  ) THEN 'ARS'
  ELSE NULL
END
WHERE importe_origen IS NULL;

ALTER TABLE public.kits
  ADD COLUMN IF NOT EXISTS criterio_costo text NOT NULL DEFAULT 'COMPONENTES';

ALTER TABLE public.kits
  DROP CONSTRAINT IF EXISTS kits_criterio_costo_check;
ALTER TABLE public.kits
  ADD CONSTRAINT kits_criterio_costo_check CHECK (criterio_costo IN ('COMPONENTES', 'MANUAL'));

CREATE TABLE IF NOT EXISTS public.kit_precio (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_kit integer NOT NULL REFERENCES public.kits(id) ON DELETE CASCADE,
  id_tipo_precio integer NOT NULL REFERENCES public.tipo_precio(id),
  precio numeric(14, 2) NOT NULL DEFAULT 0,
  porcentaje_ganancia numeric(10, 2) NOT NULL DEFAULT 0,
  modo_calculo text NOT NULL DEFAULT 'MARGEN_COSTO' CHECK (modo_calculo IN ('MARGEN_COSTO', 'FIJO_ARS', 'FIJO_MONEDA')),
  importe_origen numeric,
  moneda_origen text CHECK (moneda_origen IS NULL OR moneda_origen IN ('ARS', 'USD', 'EUR', 'BRL')),
  referencia_cotizacion text CHECK (referencia_cotizacion IS NULL OR referencia_cotizacion IN ('OFICIAL', 'BLUE', 'MEP', 'CCL')),
  lado_cotizacion text CHECK (lado_cotizacion IS NULL OR lado_cotizacion IN ('COMPRA', 'VENTA')),
  tipo_recargo_cotizacion text CHECK (tipo_recargo_cotizacion IS NULL OR tipo_recargo_cotizacion IN ('PORCENTAJE', 'MONTO_FIJO')),
  recargo_cotizacion numeric,
  cotizacion_usada numeric,
  actualizado_origen_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT NOW(),
  updated_at timestamptz NOT NULL DEFAULT NOW(),
  CONSTRAINT kit_precio_unico UNIQUE (id_kit, id_tipo_precio)
);

CREATE INDEX IF NOT EXISTS idx_producto_precio_moneda_origen
  ON public.producto_precio (moneda_origen, referencia_cotizacion)
  WHERE modo_calculo = 'FIJO_MONEDA';

CREATE INDEX IF NOT EXISTS idx_kit_precio_moneda_origen
  ON public.kit_precio (moneda_origen, referencia_cotizacion)
  WHERE modo_calculo = 'FIJO_MONEDA';

CREATE TABLE IF NOT EXISTS public.precio_moneda_historial (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo_entidad text NOT NULL CHECK (tipo_entidad IN ('ITEM', 'KIT')),
  id_entidad integer NOT NULL,
  id_tipo_precio integer NOT NULL REFERENCES public.tipo_precio(id),
  motivo text NOT NULL,
  modo_calculo text NOT NULL,
  importe_origen numeric,
  moneda_origen text,
  cotizacion_usada numeric,
  precio_ars numeric NOT NULL,
  created_at timestamptz NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_precio_moneda_historial_entidad
  ON public.precio_moneda_historial (tipo_entidad, id_entidad, created_at DESC);

CREATE TABLE IF NOT EXISTS public.mercadolibre_actualizacion_precio (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_publicacion integer NOT NULL REFERENCES public.mercadolibre_publicacion(id) ON DELETE CASCADE,
  precio numeric(14, 2) NOT NULL CHECK (precio > 0),
  estado text NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE', 'PROCESANDO', 'COMPLETADA', 'ERROR')),
  intentos integer NOT NULL DEFAULT 0,
  ultimo_error text,
  procesado_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT NOW(),
  updated_at timestamptz NOT NULL DEFAULT NOW(),
  CONSTRAINT mercadolibre_actualizacion_precio_unica UNIQUE (id_publicacion)
);

CREATE INDEX IF NOT EXISTS idx_mercadolibre_actualizacion_precio_pendiente
  ON public.mercadolibre_actualizacion_precio (estado, created_at)
  WHERE estado IN ('PENDIENTE', 'ERROR');

COMMIT;
