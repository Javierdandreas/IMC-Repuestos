BEGIN;

CREATE TABLE IF NOT EXISTS public.multimoneda_configuracion (
  id smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  moneda_default text NOT NULL DEFAULT 'ARS' CHECK (moneda_default IN ('ARS', 'USD', 'EUR', 'BRL')),
  referencia_default text NOT NULL DEFAULT 'OFICIAL' CHECK (referencia_default IN ('OFICIAL', 'BLUE', 'MEP', 'CCL')),
  lado_default text NOT NULL DEFAULT 'VENTA' CHECK (lado_default IN ('COMPRA', 'VENTA')),
  tipo_recargo_default text NOT NULL DEFAULT 'PORCENTAJE' CHECK (tipo_recargo_default IN ('PORCENTAJE', 'MONTO_FIJO')),
  recargo_default numeric NOT NULL DEFAULT 0 CHECK (recargo_default >= 0),
  umbral_aprobacion_porcentaje numeric NOT NULL DEFAULT 5 CHECK (umbral_aprobacion_porcentaje >= 0 AND umbral_aprobacion_porcentaje <= 100),
  updated_at timestamptz NOT NULL DEFAULT NOW()
);

INSERT INTO public.multimoneda_configuracion (id)
VALUES (1)
ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.moneda_cotizacion (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  moneda text NOT NULL CHECK (moneda IN ('ARS', 'USD', 'EUR', 'BRL')),
  referencia text NOT NULL CHECK (referencia IN ('OFICIAL', 'BLUE', 'MEP', 'CCL')),
  valor_compra numeric,
  valor_venta numeric,
  estado text NOT NULL DEFAULT 'VIGENTE' CHECK (estado IN ('VIGENTE', 'ERROR')),
  fuente text NOT NULL DEFAULT 'MANUAL' CHECK (fuente IN ('MANUAL', 'AUTOMATICA')),
  observacion text,
  actualizado_at timestamptz NOT NULL DEFAULT NOW(),
  created_at timestamptz NOT NULL DEFAULT NOW(),
  CONSTRAINT moneda_cotizacion_valor_check CHECK (
    (estado = 'ERROR') OR COALESCE(valor_compra, valor_venta) IS NOT NULL
  ),
  CONSTRAINT moneda_cotizacion_no_negativa CHECK (
    (valor_compra IS NULL OR valor_compra > 0) AND (valor_venta IS NULL OR valor_venta > 0)
  )
);

CREATE INDEX IF NOT EXISTS idx_moneda_cotizacion_consulta
  ON public.moneda_cotizacion (moneda, referencia, actualizado_at DESC);

INSERT INTO public.moneda_cotizacion (moneda, referencia, valor_compra, valor_venta, fuente, observacion)
SELECT 'ARS', 'OFICIAL', 1, 1, 'MANUAL', 'Base del sistema'
WHERE NOT EXISTS (
  SELECT 1 FROM public.moneda_cotizacion WHERE moneda = 'ARS' AND referencia = 'OFICIAL' AND estado = 'VIGENTE'
);

CREATE TABLE IF NOT EXISTS public.proveedor_moneda_configuracion (
  id_proveedor integer PRIMARY KEY REFERENCES public.proveedores(id) ON DELETE CASCADE,
  moneda text NOT NULL CHECK (moneda IN ('ARS', 'USD', 'EUR', 'BRL')),
  referencia text NOT NULL CHECK (referencia IN ('OFICIAL', 'BLUE', 'MEP', 'CCL')),
  lado text NOT NULL CHECK (lado IN ('COMPRA', 'VENTA')),
  tipo_recargo text NOT NULL CHECK (tipo_recargo IN ('PORCENTAJE', 'MONTO_FIJO')),
  recargo numeric NOT NULL DEFAULT 0 CHECK (recargo >= 0),
  updated_at timestamptz NOT NULL DEFAULT NOW()
);

ALTER TABLE public.proveedor_importacion
  ADD COLUMN IF NOT EXISTS moneda_origen text,
  ADD COLUMN IF NOT EXISTS referencia_cotizacion text,
  ADD COLUMN IF NOT EXISTS lado_cotizacion text,
  ADD COLUMN IF NOT EXISTS tipo_recargo_cotizacion text,
  ADD COLUMN IF NOT EXISTS recargo_cotizacion numeric,
  ADD COLUMN IF NOT EXISTS cotizacion_usada numeric,
  ADD COLUMN IF NOT EXISTS id_moneda_cotizacion integer REFERENCES public.moneda_cotizacion(id);

ALTER TABLE public.proveedor_importacion_item
  ADD COLUMN IF NOT EXISTS precio_origen numeric,
  ADD COLUMN IF NOT EXISTS moneda_origen text,
  ADD COLUMN IF NOT EXISTS cotizacion_usada numeric,
  ADD COLUMN IF NOT EXISTS costo_ars_calculado numeric;

COMMENT ON TABLE public.moneda_cotizacion IS 'Historial de cotizaciones manuales o automaticas. Los calculos siempre usan la ultima fila VIGENTE.';
COMMENT ON TABLE public.proveedor_moneda_configuracion IS 'Excepcion de moneda por proveedor. La ausencia de fila usa la configuracion global.';

COMMIT;
